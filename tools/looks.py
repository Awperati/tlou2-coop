"""Dump look records from dc1/look2/characters.bin (extract it with tools/dsar.py first).
  python -I tools/looks.py <characters.bin> [name filter]
  python -I tools/looks.py <characters.bin> --ini > config/looks.ini   (package lists for the mod's look swap)
Record layout (pointers are file offsets): +0x08 name, +0x10 skeleton name,
+0xA0/+0xA8 mesh parts, +0xB0/+0xB8 cloth, +0xC0/+0xC8 dependency packages,
+0xD0/+0xD8 animation packages. Lists are {u64 ptr, u32 count, u32 0xffffffff};
each entry is a u64 pointer, either to the name or to a struct with the name pointer at +0x10. Prints one line per look:
  <look> | skel <name> | parts a,b | cloth c,d | deps e,f | anims g,h
"""
import struct, sys

d = open(sys.argv[1], 'rb').read()
ini = '--ini' in sys.argv
args = [a for a in sys.argv[2:] if a != '--ini']
flt = args[0] if args else ''
n = len(d)


def cstr(p):
    if not 0 < p < n: return None
    e = d.find(b'\0', p, p + 128)
    if e <= p: return None
    s = d[p:e]
    if not all(32 < c < 127 for c in s): return None
    return s.decode()


def lst(off, strict=True):
    p, cnt, tag = struct.unpack_from('<QII', d, off)
    if tag != 0xFFFFFFFF or cnt > 200 or (cnt and not 0 < p < n): return None
    out = []
    for i in range(cnt):
        e = struct.unpack_from('<Q', d, p + 8 * i)[0]
        s = cstr(e)
        if s is None and 0 < e < n - 0x18: s = cstr(struct.unpack_from('<Q', d, e + 0x10)[0])
        if s is None:
            if strict: return None
            continue
        out.append(s)
    return out


seen = set()
if ini:
    print('; Generated by tools/looks.py from bin.psarc dc1/look2/characters.bin. Do not edit by hand.')
    print('; parts = mesh parts + cloth; deps/anims = other packages the look lists.')
    print()
for r in range(0, n - 0xE0, 8):
    if struct.unpack_from('<I', d, r + 0xAC)[0] != 0xFFFFFFFF: continue
    if struct.unpack_from('<I', d, r + 0xBC)[0] != 0xFFFFFFFF: continue
    name = cstr(struct.unpack_from('<Q', d, r + 8)[0])
    if not name or name in seen or flt not in name: continue
    lists = [lst(r + o, o == 0xA0) for o in (0xA0, 0xB0, 0xC0, 0xD0)]
    if any(x is None for x in lists): continue
    seen.add(name)
    skel = cstr(struct.unpack_from('<Q', d, r + 0x10)[0]) or '?'
    if not skel.endswith('skel'): continue   # mesh-part records share the list layout
    if ini:
        print(f"[look.{name}]")
        print(f"skel = {skel}")
        print(f"parts = {', '.join(lists[0] + lists[1])}")
        print(f"deps = {', '.join(lists[2])}")
        print(f"anims = {', '.join(lists[3])}")
        print()
        continue
    print(f"{name} | skel {skel} | parts {','.join(lists[0])} | cloth {','.join(lists[1])} | deps {','.join(lists[2])} | anims {','.join(lists[3])}")
